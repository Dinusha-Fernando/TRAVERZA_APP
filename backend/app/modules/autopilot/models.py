import uuid
from datetime import UTC, datetime

from sqlalchemy import Boolean, DateTime, Float, ForeignKey, Integer, String, Text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base, TimestampMixin, UUIDMixin


class DisruptionEvent(Base, UUIDMixin, TimestampMixin):
    """
    A verified operational disruption event ingested by TRAVERZA Journey Autopilot.
    Governed by Section 3 of the TRAVERZA 2.0 Product Strategy.
    """

    __tablename__ = "disruption_events"

    trip_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("trips.id", ondelete="CASCADE"), nullable=False, index=True
    )

    # Category: 'FLIGHT_DELAY', 'WEATHER_ROAD_DISRUPTION', 'DRIVER_CANCEL', 'PROVIDER_UNRESPONSIVE', 'VENUE_OVERLAP'
    event_type: Mapped[str] = mapped_column(String(50), nullable=False, index=True)

    # Severity: 'INFO', 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'
    severity: Mapped[str] = mapped_column(String(20), default="MEDIUM", nullable=False)

    # Source & Provenance
    source: Mapped[str] = mapped_column(String(100), nullable=False)  # e.g., 'SRILANKAN_AIRLINES_FEED', 'DMC_WEATHER_ADVISORY'
    observed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC), nullable=False
    )
    valid_until: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    freshness_seconds: Mapped[int] = mapped_column(Integer, default=0, nullable=False)

    summary: Mapped[str] = mapped_column(String(255), nullable=False)
    details_json: Mapped[str] = mapped_column(Text, default="{}", nullable=False)

    # Status: 'DETECTED', 'ASSESSED', 'PROPOSED', 'RESOLVED', 'DISMISSED'
    status: Mapped[str] = mapped_column(String(50), default="DETECTED", nullable=False, index=True)

    # Idempotency key prevents duplicate disruption ingestion
    idempotency_key: Mapped[str] = mapped_column(String(100), unique=True, nullable=False, index=True)

    # Proposals generated for this disruption
    proposals = relationship("AutopilotProposal", back_populates="disruption_event", cascade="all, delete-orphan")


class AutopilotProposal(Base, UUIDMixin, TimestampMixin):
    """
    Candidate resolution proposal generated by the Autopilot 6-step loop.
    Enforces the Non-Negotiable Safety Rule: Consequential changes require explicit human authorization.
    """

    __tablename__ = "autopilot_proposals"

    trip_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("trips.id", ondelete="CASCADE"), nullable=False, index=True
    )
    disruption_event_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("disruption_events.id", ondelete="CASCADE"), nullable=False, index=True
    )

    title: Mapped[str] = mapped_column(String(255), nullable=False)
    explanation: Mapped[str] = mapped_column(Text, nullable=False)

    # Impact Deltas
    timing_delta_minutes: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    cost_delta_minor: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    currency: Mapped[str] = mapped_column(String(3), default="LKR", nullable=False)

    confidence_score: Mapped[float] = mapped_column(Float, default=1.0, nullable=False)
    proposed_actions_json: Mapped[str] = mapped_column(Text, default="[]", nullable=False)

    # Authorization Gates
    requires_authorization: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    # Status: 'PENDING_AUTHORIZATION', 'APPROVED', 'REJECTED', 'EXECUTED'
    authorization_status: Mapped[str] = mapped_column(String(50), default="PENDING_AUTHORIZATION", nullable=False, index=True)

    authorized_by_id: Mapped[uuid.UUID | None] = mapped_column(UUID(as_uuid=True), nullable=True)
    authorized_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    execution_notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    disruption_event = relationship("DisruptionEvent", back_populates="proposals")
